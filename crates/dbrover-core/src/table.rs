//! Tables as a statement names them, and what editing their rows needs to know.

use std::collections::BTreeMap;

use crate::Quoting;

/// A name as written in SQL. Whether it was quoted matters: PostgreSQL folds unquoted names
/// to lowercase, and SQLite matches them ignoring case.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct Identifier {
    pub name: String,
    pub quoted: bool,
}

impl Identifier {
    /// The identifier as SQL text, quoted as it was written.
    pub fn to_sql(&self, quoting: Quoting) -> String {
        if self.quoted {
            quoting.identifier(&self.name)
        } else {
            self.name.clone()
        }
    }
}

/// `[schema.]table`, as a statement names it.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct RelationName {
    pub schema: Option<Identifier>,
    pub name: Identifier,
}

impl RelationName {
    pub fn to_sql(&self, quoting: Quoting) -> String {
        match &self.schema {
            Some(schema) => format!("{}.{}", schema.to_sql(quoting), self.name.to_sql(quoting)),
            None => self.name.to_sql(quoting),
        }
    }
}

/// A table resolved by the database: where it really lives, its columns, its primary key,
/// and the foreign keys that tie it to other tables.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TableDescription {
    pub schema: String,
    pub name: String,
    /// In table order.
    pub columns: Vec<ColumnDescription>,
    /// In key order. Empty if the table has none.
    pub primary_key: Vec<String>,
    /// The table's own foreign keys, pointing at other tables (or itself).
    pub foreign_keys: Vec<ForeignKey>,
    /// Other tables' foreign keys that point at this one, including its own that point at
    /// itself.
    pub referenced_by: Vec<ForeignKey>,
}

/// A table's name as the database resolved it.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct TableName {
    pub schema: String,
    pub name: String,
}

/// A foreign key: each row's values in `columns` of `table` are those of a row of
/// `referenced` in `referenced_columns`, column for column, unless one of them is `NULL`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ForeignKey {
    pub table: TableName,
    pub columns: Vec<String>,
    pub referenced: TableName,
    pub referenced_columns: Vec<String>,
}

impl ForeignKey {
    /// The columns paired with the ones they refer to, in key order.
    pub fn column_pairs(&self) -> impl Iterator<Item = (&str, &str)> {
        self.columns
            .iter()
            .map(String::as_str)
            .zip(self.referenced_columns.iter().map(String::as_str))
    }
}

/// One column of a described table, as the database reports it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ColumnDescription {
    pub name: String,
    /// As the database spells the type, which may differ from how it was written:
    /// `character varying(20)` for `varchar(20)` on PostgreSQL, `int` for `integer` on MySQL.
    pub data_type: String,
    pub nullable: bool,
    /// The default's expression as the database keeps it, e.g. `nextval('orders_id_seq'::regclass)`.
    pub default: Option<String>,
    /// Whether the database numbers the column's values itself, and how.
    pub identity: Option<Identity>,
}

/// A column the database numbers itself: PostgreSQL's and SQL Server's identity columns,
/// MySQL's `AUTO_INCREMENT` and SQLite's `AUTOINCREMENT`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Identity {
    pub generation: IdentityGeneration,
    /// The first value; 1 unless the column says otherwise. Only PostgreSQL and SQL Server
    /// keep it on the column.
    pub start: i64,
    /// The step between values; 1 unless the column says otherwise, as for `start`.
    pub increment: i64,
}

/// Whether an insert may give an identity column a value of its own.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IdentityGeneration {
    /// The database always numbers it, and refuses a value (PostgreSQL's `GENERATED ALWAYS`,
    /// SQL Server's `IDENTITY` unless `IDENTITY_INSERT` is on).
    Always,
    /// The database numbers it when an insert leaves it out (PostgreSQL's `GENERATED BY
    /// DEFAULT`, MySQL's `AUTO_INCREMENT`, SQLite's `AUTOINCREMENT`).
    ByDefault,
}

impl Identity {
    /// Numbered from 1, one at a time.
    pub const fn counting(generation: IdentityGeneration) -> Self {
        Self {
            generation,
            start: 1,
            increment: 1,
        }
    }
}

/// What a foreign key does when the row it points at is deleted or its key updated.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash)]
pub enum ReferentialAction {
    /// Refuse the change, checked at the end of the statement. Every dialect's default, so
    /// it is never written.
    #[default]
    NoAction,
    /// Refuse the change at once.
    Restrict,
    Cascade,
    SetNull,
    SetDefault,
}

impl ReferentialAction {
    pub fn sql(self) -> &'static str {
        match self {
            Self::NoAction => "NO ACTION",
            Self::Restrict => "RESTRICT",
            Self::Cascade => "CASCADE",
            Self::SetNull => "SET NULL",
            Self::SetDefault => "SET DEFAULT",
        }
    }

    /// The action a catalog names, as SQL writes it (`SET NULL`) or with an underscore
    /// (SQL Server's `SET_NULL`), in any case. `None` for anything else.
    pub fn from_catalog(name: &str) -> Option<Self> {
        let name = name.trim().replace('_', " ").to_ascii_uppercase();
        [
            Self::NoAction,
            Self::Restrict,
            Self::Cascade,
            Self::SetNull,
            Self::SetDefault,
        ]
        .into_iter()
        .find(|action| action.sql() == name)
    }
}

/// A table's constraints as its catalog names them, which [`TableDescription`] leaves out:
/// what changing the table needs to keep, or to drop by name.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct TableConstraints {
    /// The primary key constraint's name, where the database gives it one.
    pub primary_key_name: Option<String>,
    pub unique_keys: Vec<UniqueConstraint>,
    /// The table's own foreign keys.
    pub foreign_keys: Vec<ForeignKeyConstraint>,
    pub checks: Vec<CheckConstraint>,
    /// Column → the name of its default's constraint, on SQL Server, which keeps each default
    /// as a constraint.
    pub default_names: BTreeMap<String, String>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UniqueConstraint {
    /// `None` where the database keeps no name (SQLite).
    pub name: Option<String>,
    /// In key order.
    pub columns: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ForeignKeyConstraint {
    /// `None` where the database keeps no name (SQLite).
    pub name: Option<String>,
    pub columns: Vec<String>,
    pub referenced: TableName,
    /// The columns of `referenced` each of `columns` refers to, in the same order.
    pub referenced_columns: Vec<String>,
    pub on_delete: ReferentialAction,
    pub on_update: ReferentialAction,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CheckConstraint {
    pub name: Option<String>,
    /// The condition as the database keeps it, without `CHECK`.
    pub expression: String,
}

impl TableDescription {
    pub fn has_column(&self, name: &str) -> bool {
        self.columns.iter().any(|column| column.name == name)
    }

    pub fn column_names(&self) -> impl Iterator<Item = &str> {
        self.columns.iter().map(|column| column.name.as_str())
    }

    pub fn table_name(&self) -> TableName {
        TableName {
            schema: self.schema.clone(),
            name: self.name.clone(),
        }
    }

    /// The table's name for generated SQL: schema-qualified and always quoted, so it means
    /// exactly this table whatever the search path and whatever the names spell.
    pub fn qualified_name(&self, quoting: Quoting) -> String {
        format!(
            "{}.{}",
            quoting.identifier(&self.schema),
            quoting.identifier(&self.name)
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn writes_names_as_they_were_written_and_quotes_generated_ones() {
        let name = RelationName {
            schema: Some(Identifier {
                name: "public".to_owned(),
                quoted: false,
            }),
            name: Identifier {
                name: "Order \"Items\"".to_owned(),
                quoted: true,
            },
        };
        assert_eq!(
            name.to_sql(Quoting::STANDARD),
            "public.\"Order \"\"Items\"\"\""
        );
        let described = TableDescription {
            schema: "public".to_owned(),
            name: "order".to_owned(),
            columns: vec![],
            primary_key: vec![],
            foreign_keys: vec![],
            referenced_by: vec![],
        };
        assert_eq!(
            described.qualified_name(Quoting::STANDARD),
            "\"public\".\"order\""
        );
    }
}
