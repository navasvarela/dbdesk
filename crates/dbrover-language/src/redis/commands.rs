//! Every command and subcommand of Redis 8 and Valkey 9, with what the server says of it.
//!
//! Generated from the command definitions in Redis 8.10.3's and Valkey 9.1.3's sources
//! (`src/commands/*.json`), from which the servers answer `COMMAND INFO` and `COMMAND DOCS`;
//! a command only one of them has is listed too. Where their arities differ, the table keeps
//! the one that accepts more arguments. Don't edit the table by hand: regenerate it.

/// One of the flags `COMMAND INFO` gives a command, among those DbRover acts on.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Flag {
    /// Reads keys and never changes them.
    Readonly,
    /// May change keys.
    Write,
    /// Administers the server.
    Admin,
    /// May wait for something to happen before answering, as `BLPOP` does.
    Blocking,
}

/// What the table says of a command.
#[derive(Debug, PartialEq, Eq)]
pub struct CommandSpec {
    /// Lowercase; `container|subcommand` for a subcommand, as `COMMAND INFO` names it.
    pub name: &'static str,
    /// How many arguments it takes, its name included: exactly that many, or, when negative,
    /// at least that many (`-2` is one argument or more).
    pub arity: i16,
    pub flags: &'static [Flag],
    /// Its arguments, as Redis's documentation writes them: `key field value [field value ...]`.
    pub syntax: &'static str,
}

impl CommandSpec {
    pub fn has(&self, flag: Flag) -> bool {
        self.flags.contains(&flag)
    }

    /// Whether `count` arguments, the name and a subcommand's name included, fit its arity.
    pub fn accepts(&self, count: usize) -> bool {
        let arity = usize::from(self.arity.unsigned_abs());
        if self.arity < 0 {
            count >= arity
        } else {
            count == arity
        }
    }
}

const fn command(
    name: &'static str,
    arity: i16,
    flags: &'static [Flag],
    syntax: &'static str,
) -> CommandSpec {
    CommandSpec {
        name,
        arity,
        flags,
        syntax,
    }
}

/// The command `name` (lowercase), if the table lists it.
pub(super) fn find(name: &str) -> Option<&'static CommandSpec> {
    COMMANDS
        .binary_search_by(|spec| spec.name.cmp(name))
        .ok()
        .map(|index| &COMMANDS[index])
}

