#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lists_are_sorted_unique_and_lowercase() {
        for list in [POSTGRES, SQLITE] {
            assert!(list.windows(2).all(|pair| pair[0] < pair[1]), "{list:?}");
            assert!(list.iter().all(|name| {
                name.chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
            }));
        }
    }
}
